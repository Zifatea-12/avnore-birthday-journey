import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import {
  Outlet,
  Link,
  createRootRouteWithContext,
  useRouter,
  HeadContent,
  Scripts,
} from "@tanstack/react-router";
import { type ReactNode, useState, useRef } from "react";
import { Volume2, VolumeX } from "lucide-react";
import appCss from "../styles.css?url";

export function AudioPlayer() {
  const [isPlaying, setIsPlaying] = useState(false);
  const audioRef = useRef<HTMLAudioElement | null>(null);

  const toggleAudio = () => {
    if (!audioRef.current) return;

    if (isPlaying) {
      audioRef.current.pause();
      setIsPlaying(false);
    } else {
      audioRef.current.volume = 0.3; // Setel volume ke 30%
      
      audioRef.current
        .play()
        .then(() => {
          setIsPlaying(true);
        })
        .catch((error) => {
          console.error("Gagal memutar audio. Cek lokasi file atau izin browser:", error);
        });
    }
  };

  return (
    <>
      {/* Sesuaikan huruf 'audio' di bawah dengan nama folder asli di public/ */}
      <audio ref={audioRef} src="/audio/bg-music.mp3" loop preload="auto" />

      <button
        type="button"
        onClick={toggleAudio}
        className="fixed top-5 right-5 z-50 flex h-11 w-11 items-center justify-center rounded-full bg-[#171817] text-[#E9E4D7] border border-[#A18A57]/40 hover:border-[#A18A57] transition-all shadow-lg focus:outline-none cursor-pointer"
        title={isPlaying ? "Matikan Musik" : "Putar Musik"}
      >
        {isPlaying ? <Volume2 size={18} /> : <VolumeX size={18} />}
      </button>
    </>
  );
}

